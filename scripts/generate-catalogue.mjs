#!/usr/bin/env node
/*
 * generate-catalogue — catalogue.json, the committed machine-readable index of
 * the corpus.
 *
 * Every human-facing surface here is generated from the same sources — the
 * meta/ sidecars and the two `" @…` lines on each class — but each one is
 * shaped for a reader: SAMPLES.md is markdown rows, api.md is a coverage
 * table, the Pages catalogue is a site whose apps.json is deliberately NOT
 * committed (web/README.md). An AI tool pointed at the repository therefore
 * had to either parse markdown or re-derive everything from 400+ sidecars.
 * The sibling repositories ship a committed index for exactly this consumer;
 * this is the same artefact for this corpus: one JSON entry per port, the
 * sidecar facts joined with the class-scan facts, plus a top-level block that
 * says what this repository IS — including the class-name trap a tool that
 * has seen abap2UI5/samples will otherwise walk into.
 *
 * Offline and dependency-free on purpose: it runs inside `npm run gates`,
 * which needs no node_modules. That is also why there is no linter pass here —
 * the derived facts (controls built, minimum UI5 release) live in the Pages
 * apps.json, which a deploy regenerates; this file carries only what is
 * committed fact in the tree.
 *
 *   node scripts/generate-catalogue.mjs          write catalogue.json
 *   node scripts/generate-catalogue.mjs --check  fail if it is stale (CI)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { readDescript } from './lib/descript.mjs';
import { walkFiles } from './lib/src-tree.mjs';
import { libraryOf, descriptLibrary } from './lib/ui5-libs.mjs';
import { loadUniverseSnapshot } from './lib-universe.mjs';
import { sampleNames } from './lib/sample-names.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'catalogue.json');
const CHECK = process.argv.includes('--check');
const nameOf = sampleNames(ROOT);

/* The in-system overview app implements z2ui5_if_app like every port, but it
 * rebuilds no demo kit original — it is the table that lists them. Same
 * exclusion as the search index. */
const OVERVIEW = 'z2ui5_cl_smpc_app_000';

const entries = [];
for (const file of walkFiles(path.join(ROOT, 'src'), '.clas.abap')) {
  const source = fs.readFileSync(file, 'utf8');
  if (!/INTERFACES\s+z2ui5_if_app\s*\./i.test(source)) continue;

  const cls = path.basename(file, '.clas.abap');
  if (cls === OVERVIEW) continue;
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  const metaPath = path.join(ROOT, 'meta', `${cls}.json`);
  const meta = fs.existsSync(metaPath) ? JSON.parse(fs.readFileSync(metaPath, 'utf8')) : null;
  const descript = readDescript(file);
  const collection = !meta && cls.includes('_sapui5_');

  entries.push({
    class: cls,
    file: rel,
    /* The first path level — what a system needs to run it (AGENTS.md §3);
     * the `categories` block up top spells the three out. */
    category: rel.split('/').slice(0, 2).join('/'),
    /* The library the port is filed under: the entity's ship-library for a
     * port (the namespace is not the library — see lib/ui5-libs.mjs), the
     * DESCRIPT's head for the src/03 collection, whose sidecar-less classes
     * name their library there. */
    library: meta?.entity ? libraryOf(meta.entity) : descriptLibrary(descript, []),
    sample: meta?.sample || '',
    entity: meta?.entity || '',
    /* The demo kit's own name for the sample (both snapshot blocks, cleaned —
     * scripts/lib/sample-names.mjs); the whole DESCRIPT only for the src/03
     * collection, which has no demo kit sample to be named after. */
    title: (meta?.sample && nameOf(meta.sample)) || descript,
    summary: (source.match(/^" @summary (.+?)\r?$/m) || [, ''])[1].trim(),
    keywords: (source.match(/^" @keywords (.+?)\r?$/m) || [, ''])[1].trim(),
    status: meta?.status || (collection ? 'collection' : ''),
    deviations: [...new Set((meta?.deviations || []).map((d) => d.type))].sort(),
  });
}
entries.sort((a, b) => a.class.localeCompare(b.class));

const byStatus = {};
for (const e of entries) byStatus[e.status] = (byStatus[e.status] || 0) + 1;

const top = {
  note: 'Generated by scripts/generate-catalogue.mjs from the meta/ sidecars and the classes — do not edit by hand; run `npm run catalogue` (AGENTS.md §7).',
  repo: 'abap2UI5/samples-controls',
  role: 'step 2 of 3 — the control reference: every in-scope UI5 demo kit '
    + 'sample rebuilt 1:1 as an abap2UI5 class. Learn the patterns in '
    + 'abap2UI5/samples first; what needs your system (OData, RAP, APC, the '
    + 'launchpad) is in abap2UI5/samples-stack.',
  caveat: 'Class names: this repository uses the Z2UI5_CL_SMPC_* prefix, '
    + 'abap2UI5/samples uses Z2UI5_CL_SMP_* — one character apart, with '
    + 'INDEPENDENT numbering. z2ui5_cl_smp_app_042 and z2ui5_cl_smpc_app_042 '
    + 'are unrelated samples: match on the full class name, never on the '
    + 'number or a fuzzy prefix.',
  categories: {
    'src/01': 'ports that run on any OpenUI5/SAPUI5 from 1.71 on',
    'src/02': 'ports that need a UI5 runtime newer than 1.71',
    'src/03': 'SAPUI5-only collection — hand-written samples, not 1:1 ports; no sidecar, no demo kit original',
  },
  statuses: {
    checked: 'a human watched this port run in a real system',
    reviewed: 'read against its original, not yet run',
    generated: 'machine-written, not yet reviewed',
    collection: 'src/03 — outside the port machinery',
  },
  deviationTypes: {
    POST_171: 'keeps something newer than UI5 1.71, for fidelity — the port needs a matching runtime',
    DROPPED_171: 'something newer than UI5 1.71 was left out',
    IMPROVISED: 'the original construct has no abap2UI5 equivalent yet',
    LIVE_TEST: 'an interaction still to be confirmed in a running system',
    NOTE: 'a documented difference from the original',
  },
  ui5Snapshot: loadUniverseSnapshot().release,
  counts: { entries: entries.length, byStatus },
};

/* One line per entry, so a port PR diffs as one added line — the same reason
 * SAMPLES.md is one row per port. The header block is indented normally. */
const head = JSON.stringify(top, null, 2);
const body = entries.map((e) => `    ${JSON.stringify(e)}`).join(',\n');
const page = `${head.slice(0, -2)},\n  "ports": [\n${body}\n  ]\n}\n`;

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== page) {
    console.error('catalogue.json is stale — run `npm run catalogue` and commit the result.');
    process.exit(1);
  }
  console.log(`catalogue.json: current (${entries.length} entries)`);
} else {
  fs.writeFileSync(OUT, page);
  console.log(`catalogue.json: ${entries.length} entries (${Object.entries(byStatus).map(([k, v]) => `${v} ${k}`).join(', ')})`);
}
